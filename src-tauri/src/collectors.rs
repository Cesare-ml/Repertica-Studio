// Only flat paths generated by Repertica can be read or unlinked.
fn valid_media_file(path: &str) -> bool {
    if path.contains('\\') { return false; }
    let mut components = Path::new(path).components();
    matches!(components.next(), Some(Component::Normal(root)) if root == "media")
        && matches!(components.next(), Some(Component::Normal(_)))
        && components.next().is_none()
}

// Refuse a replaced media/ symlink before writing, reading or deleting photos.
fn require_regular_media_dir(db: &Database) -> Result<(), String> {
    let kind = fs::symlink_metadata(db.directory.join("media")).map_err(err)?.file_type();
    if kind.is_symlink() || !kind.is_dir() {
        return Err("La cartella media non è una directory locale regolare".into());
    }
    Ok(())
}

