// A collector photograph might be replaced or enlarged outside Repertica after
// import. Cap the actual read, not only file metadata, before sending IPC data.
fn collector_image_data_core(db: &Database, image_id: &str) -> Result<String, String> {
    require_regular_media_dir(db)?;
    let conn = db.conn.lock().map_err(err)?;
    let relative: String = conn.query_row("SELECT image_path FROM collector_images WHERE id=?1",
        params![image_id], |r| r.get(0))
        .optional().map_err(err)?.ok_or("Fotografia non trovata")?;
    if !valid_media_file(&relative) { return Err("Percorso media non valido".into()); }
    let path = db.directory.join(relative);
    let kind = fs::symlink_metadata(&path).map_err(err)?.file_type();
    if kind.is_symlink() || !kind.is_file() { return Err("File media non valido".into()); }
    let file = fs::File::open(&path).map_err(err)?;
    let size = file.metadata().map_err(err)?.len();
    if size == 0 || size > MAX_COLLECTOR_PREVIEW_BYTES {
        return Err("Fotografia vuota o troppo grande (massimo 12 MiB)".into());
    }
    // A second size check on the bytes also handles a file growing during read.
    let mut bytes = Vec::new();
    file.take(MAX_COLLECTOR_PREVIEW_BYTES + 1)
        .read_to_end(&mut bytes).map_err(err)?;
    if bytes.is_empty() || bytes.len() as u64 > MAX_COLLECTOR_PREVIEW_BYTES {
        return Err("Fotografia vuota o troppo grande (massimo 12 MiB)".into());
    }
    let (_, mime) = image_type(&bytes).ok_or("Formato file non valido")?;
    Ok(format!("data:{mime};base64,{}", STANDARD.encode(bytes)))
}

